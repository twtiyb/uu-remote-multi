#!/usr/bin/env bash
set -euo pipefail
TASK_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MODE="${1:-run}"
case "$MODE" in
  run|--verify|--debug|--logs|--telemetry) ;;
  *) echo "usage: $0 [--verify|--debug|--logs|--telemetry]" >&2; exit 2 ;;
esac

python3 - "$TASK_ROOT" <<'PY'
import datetime
import json
import os
import signal
import subprocess
import sys
from pathlib import Path
root = Path(sys.argv[1])
app = root / 'outputs/UU Remote Account 2.app'
if app.exists():
    manifest = app / 'Contents/Resources/uu-multi-build.json'
    if not manifest.exists() or json.loads(manifest.read_text()).get('tool') != 'uu-remote-multi':
        raise SystemExit('Refusing to replace an app not generated by this tool')
    executable = str(app / 'Contents/MacOS/UURemote')
    for line in subprocess.check_output(['ps','-axo','pid,comm'], text=True).splitlines():
        fields = line.strip().split(None,1)
        if len(fields) == 2 and fields[1] == executable:
            os.kill(int(fields[0]), signal.SIGTERM)
    backup = root / 'work/build-backups' / datetime.datetime.now().strftime('%Y%m%d-%H%M%S-%f')
    backup.mkdir(parents=True)
    app.rename(backup / (app.name + '.disabled'))
PY

python3 "$TASK_ROOT/uu_remote_multi.py" --output "$TASK_ROOT/outputs/UU Remote Account 2.app"
APP_BUNDLE="$TASK_ROOT/outputs/UU Remote Account 2.app"
case "$MODE" in
  --debug) exec lldb -- "$APP_BUNDLE/Contents/MacOS/UURemote" ;;
  --logs|--telemetry)
    open -n "$APP_BUNDLE"
    exec /usr/bin/log stream --info --style compact --predicate 'subsystem BEGINSWITH "com.netease.uualt002"'
    ;;
  *) open -n "$APP_BUNDLE" ;;
esac
if [[ "$MODE" == "--verify" ]]; then
  python3 - "$APP_BUNDLE" <<'PY'
import subprocess, sys, time
from pathlib import Path
expected = str(Path(sys.argv[1]) / 'Contents/MacOS/UURemote')
for _ in range(30):
    rows = subprocess.check_output(['ps','-axo','pid,comm'],text=True).splitlines()
    if any(row.strip().split(None,1)[-1] == expected for row in rows):
        print('Generated second instance is running')
        break
    time.sleep(.1)
else:
    raise SystemExit('Second instance did not stay running')
PY
fi
